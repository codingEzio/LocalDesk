import { dirname, join, resolve } from "node:path";
import { loadSettings, type Settings } from "../backend/settings.ts";
import {
  loadRegistry,
  type PortProject,
  registryWorkspaceRoot,
} from "../backend/runtime-registry.ts";

export type ServiceOptions = {
  install: boolean;
  label: string;
  workspaceRegistry?: string;
};

export function parseServiceOptions(args: string[]): ServiceOptions {
  const options: ServiceOptions = {
    install: false,
    label: "org.localdesk.app",
  };
  const seen = new Set<string>();
  for (let i = 0; i < args.length; i++) {
    const arg = args[i];
    if (seen.has(arg)) throw new Error(`Duplicate argument: ${arg}`);
    seen.add(arg);
    if (arg === "--install" || arg === "--dry-run") {
      if (seen.has(arg === "--install" ? "--dry-run" : "--install")) {
        throw new Error("Choose --dry-run or --install");
      }
      options.install = arg === "--install";
    } else if (arg === "--label" || arg === "--workspace-registry") {
      const value = args[++i];
      if (!value || value.startsWith("--")) {
        throw new Error(`Missing ${arg} value`);
      }
      if (arg === "--label") options.label = value;
      else options.workspaceRegistry = value;
    } else throw new Error(`Unknown argument: ${arg}`);
  }
  if (!/^[A-Za-z0-9][A-Za-z0-9.-]{0,149}$/.test(options.label)) {
    throw new Error("Invalid LaunchAgent label");
  }
  return options;
}

function shell(value: string): string {
  return /^[A-Za-z0-9_./:@=-]+$/.test(value)
    ? value
    : "'" + value.replaceAll("'", "'\\''") + "'";
}
function xml(value: string): string {
  return value.replaceAll("&", "&amp;").replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;").replaceAll('"', "&quot;")
    .replaceAll("'", "&apos;");
}

export function renderService(input: {
  root: string;
  deno: string;
  processCompose: string;
  home: string;
  path: string;
  label: string;
  config?: string;
  codexHome?: string;
  dataDirectory?: string;
  workspaceRegistry?: string;
}) {
  const runtime = join(input.root, "Local/runtime");
  const composePath = join(runtime, "process-compose.yaml");
  const plistPath = join(runtime, `${input.label}.plist`);
  const command = (role: "frontend" | "backend", file: string) => {
    const prefix = input.workspaceRegistry
      ? [
        join(
          registryWorkspaceRoot(input.workspaceRegistry),
          ".runtime/run-project.sh",
        ),
        "X-LocalDesk",
        role,
        "--reclaim-port",
        "--",
      ]
      : [];
    return "exec " +
      [...prefix, input.deno, "run", "-A", join(input.root, "backend", file)]
        .map(shell).join(" ");
  };
  const compose =
    `# Generated by LocalDesk. Machine paths stay in ignored Local/runtime.
version: "0.5"
is_strict: true
is_tui_disabled: true
log_level: info
log_length: 300
log_location: ${JSON.stringify(join(runtime, "process-compose.log"))}
log_configuration:
  rotation:
    max_size_mb: 5
    max_age_days: 7
    max_backups: 2
    compress: true
processes:
  localdesk-api:
    command: ${JSON.stringify(command("backend", "main.ts"))}
    working_dir: ${JSON.stringify(input.root)}
    availability:
      restart: always
      backoff_seconds: 2
    shutdown:
      signal: 15
      timeout_seconds: 15
  localdesk-web:
    command: ${JSON.stringify(command("frontend", "web.ts"))}
    working_dir: ${JSON.stringify(input.root)}
    environment:
      - "LOCALDESK_HOST=0.0.0.0"
    depends_on:
      localdesk-api:
        condition: process_started
    availability:
      restart: always
      backoff_seconds: 2
    shutdown:
      signal: 15
      timeout_seconds: 15
`;
  const environment: Record<string, string> = {
    HOME: input.home,
    PATH: input.path,
    LOCALDESK_DENO: input.deno,
    PC_DISABLE_DOTENV: "1",
    // Process output has rotation above; discard the manager's separate debug log.
    PC_LOG_FILE: "/dev/null",
  };
  if (Deno.build.os === "darwin") {
    // Do not load bundled Mozilla roots while they retain compromised emSign G3.
    environment.DENO_TLS_CA_STORE = "";
    environment.DENO_CERT = "/opt/homebrew/etc/ca-certificates/cert.pem";
  }
  if (input.config) environment.LOCALDESK_CONFIG = input.config;
  if (input.codexHome) environment.CODEX_HOME = input.codexHome;
  if (input.dataDirectory) environment.LOCALDESK_DATA = input.dataDirectory;
  const plist = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>Label</key><string>${xml(input.label)}</string>
  <key>ProgramArguments</key><array>${
    [input.processCompose, "-f", composePath, "--no-server", "up"].map((arg) =>
      `<string>${xml(arg)}</string>`
    ).join("")
  }</array>
  <key>WorkingDirectory</key><string>${xml(input.root)}</string>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><true/>
  <key>ThrottleInterval</key><integer>5</integer>
  <key>ExitTimeOut</key><integer>35</integer>
  <key>EnvironmentVariables</key><dict>${
    Object.entries(environment).map(([key, value]) =>
      `<key>${xml(key)}</key><string>${xml(value)}</string>`
    ).join("")
  }</dict>
  <key>StandardOutPath</key><string>/dev/null</string>
  <key>StandardErrorPath</key><string>/dev/null</string>
</dict></plist>
`;
  return { runtime, composePath, plistPath, compose, plist, environment };
}

export function validateServiceRegistry(
  entry: PortProject | undefined,
  registry: string,
  root: string,
  settings: Pick<Settings, "frontendPort" | "backendPort">,
) {
  if (
    !entry || entry.lifecycle !== "active" || !entry.path ||
    resolve(registryWorkspaceRoot(registry), entry.path) !== resolve(root) ||
    !entry.endpoints.frontend || !entry.endpoints.backend ||
    entry.frontend !== settings.frontendPort ||
    entry.backend !== settings.backendPort
  ) {
    throw new Error(
      "X-LocalDesk registry path/endpoints/ports do not match local settings",
    );
  }
}

async function command(
  executable: string,
  args: string[],
  timeoutMs = 15000,
  env?: Record<string, string>,
) {
  const output = await new Deno.Command(executable, {
    args,
    env,
    stdout: "piped",
    stderr: "piped",
    signal: AbortSignal.timeout(timeoutMs),
  }).output();
  return {
    ok: output.success,
    text: new TextDecoder().decode(output.stdout),
    error: new TextDecoder().decode(output.stderr),
  };
}
async function checked(
  executable: string,
  args: string[],
  timeoutMs = 15000,
  env?: Record<string, string>,
) {
  const result = await command(executable, args, timeoutMs, env);
  if (!result.ok) {
    throw new Error(
      `${executable} ${args.join(" ")} failed: ${result.error || result.text}`,
    );
  }
  return result.text;
}
async function findExecutable(name: string) {
  for (const directory of (Deno.env.get("PATH") ?? "").split(":")) {
    if (!directory) continue;
    const candidate = resolve(directory, name);
    try {
      const stat = await Deno.stat(candidate);
      if (stat.isFile && ((stat.mode ?? 0) & 0o111) !== 0) {
        return candidate;
      }
    } catch (e) {
      if (!(e instanceof Deno.errors.NotFound)) throw e;
    }
  }
  throw new Error(`${name} is required on PATH`);
}
async function textIfPresent(path: string) {
  try {
    return await Deno.readTextFile(path);
  } catch (e) {
    if (e instanceof Deno.errors.NotFound) return null;
    throw e;
  }
}
async function atomicWrite(path: string, content: string) {
  if (await textIfPresent(path) === content) return;
  const temporary = path + "." + crypto.randomUUID() + ".tmp";
  try {
    await Deno.writeTextFile(temporary, content, {
      createNew: true,
      mode: 0o600,
    });
    await Deno.rename(temporary, path);
  } finally {
    await Deno.remove(temporary).catch((error) => {
      if (!(error instanceof Deno.errors.NotFound)) {
        console.error(
          `Temporary file cleanup failed: ${temporary}: ${String(error)}`,
        );
      }
    });
  }
}
function checkFreePorts(settings: Settings) {
  const sockets: Deno.TcpListener[] = [];
  try {
    for (const port of [settings.frontendPort, settings.backendPort]) {
      sockets.push(Deno.listen({ hostname: "0.0.0.0", port }));
    }
  } finally {
    for (const socket of sockets) socket.close();
  }
}
function managerPid(output: string, compose: string) {
  const pid = output.match(/^\s*pid\s*=\s*(\d+)\s*$/m)?.[1];
  const args = output.match(/^\s*arguments\s*=\s*\{\s*$([\s\S]*?)^\s*\}/m)?.[1]
    ?.split("\n").map((line) => line.trim()).filter(Boolean);
  if (
    !pid || !args || args[1] !== "-f" || args[2] !== compose ||
    !/state\s*=\s*running/.test(output)
  ) {
    throw new Error("Loaded LaunchAgent does not own the generated runtime");
  }
  return Number(pid);
}
async function verifyListeners(manager: number, ports: number[]) {
  const processTable = await checked("/bin/ps", ["-axo", "pid=,ppid="], 5000);
  const parents = new Map(
    processTable.trim().split("\n").map((line) =>
      line.trim().split(/\s+/).map(Number)
    ).map(([pid, parent]) => [pid, parent]),
  );
  for (const port of ports) {
    const text = await checked("/usr/sbin/lsof", [
      "-nP",
      "-a",
      `-iTCP:${port}`,
      "-sTCP:LISTEN",
      "-Fp",
    ], 5000);
    const owners = [...text.matchAll(/^p(\d+)$/gm)].map((m) => Number(m[1]));
    if (!owners.length) throw new Error(`No listener on ${port}`);
    for (const owner of owners) {
      let pid = owner;
      const visited = new Set<number>();
      while (pid !== manager && pid > 1 && !visited.has(pid)) {
        visited.add(pid);
        pid = parents.get(pid) ?? 0;
      }
      if (pid !== manager) {
        throw new Error(`Port ${port} is not owned by this LaunchAgent`);
      }
    }
  }
}
async function waitHealthy(
  domain: string,
  label: string,
  compose: string,
  settings: Settings,
) {
  const deadline = Date.now() + 30000;
  let failure: unknown = new Error("No health response");
  while (Date.now() < deadline) {
    try {
      const loaded = await checked("/bin/launchctl", [
        "print",
        `${domain}/${label}`,
      ], 5000);
      const pid = managerPid(loaded, compose);
      await verifyListeners(pid, [settings.frontendPort, settings.backendPort]);
      for (
        const url of [
          `http://127.0.0.1:${settings.backendPort}/health`,
          `http://127.0.0.1:${settings.frontendPort}/health`,
          `http://127.0.0.1:${settings.frontendPort}/`,
        ]
      ) {
        const response = await fetch(url, {
          signal: AbortSignal.timeout(1500),
        });
        const ok = response.ok;
        if (url.endsWith("/health")) {
          const body = await response.json();
          if (!ok || body.ok !== true) throw new Error(`Health failed: ${url}`);
        } else {
          await response.body?.cancel();
          if (!ok) throw new Error(`HTTP failed: ${url}`);
        }
      }
      return;
    } catch (error) {
      failure = error;
    }
    await new Promise((resolve) => setTimeout(resolve, 250));
  }
  throw new Error(`Runtime health/ownership timed out: ${String(failure)}`);
}

export async function main(args: string[]) {
  if (args.includes("--help")) {
    console.log(
      "deno run -A scripts/service.ts [--dry-run|--install] [--label org.localdesk.app] [--workspace-registry /path/PROJECT_PORTS.json]\nDefault: generate and validate ignored Local/runtime files only. --install is macOS-only and refuses occupied ports, loaded labels or conflicting installed plists. No existing service restart or uninstall. Registry integration uses the workspace-owned stale-process policy only after a free-port installation precheck.",
    );
    return;
  }
  if (Deno.build.os !== "darwin") {
    throw new Error("LaunchAgent generation/installation requires macOS");
  }
  const options = parseServiceOptions(args);
  const root = dirname(import.meta.dirname!);
  const settings = await loadSettings(root);
  const home = Deno.env.get("HOME");
  if (!home) {
    throw new Error("HOME is required for the LaunchAgent destination");
  }
  const registryPath = options.workspaceRegistry
    ? resolve(root, options.workspaceRegistry)
    : undefined;
  const processCompose = await findExecutable("process-compose");
  const explicitConfig = Deno.env.get("LOCALDESK_CONFIG");
  const generated = renderService({
    root,
    home,
    label: options.label,
    // Keep the logical PATH entry: Homebrew replaces versioned Cellar binaries.
    deno: await findExecutable("deno"),
    processCompose,
    path: Deno.env.get("PATH") ?? "/usr/bin:/bin",
    config: explicitConfig ? resolve(root, explicitConfig) : undefined,
    workspaceRegistry: registryPath,
    codexHome: Deno.env.get("CODEX_HOME"),
    dataDirectory: dataDirectory(root),
  });
  let registryTool: string | undefined;
  if (registryPath) {
    const registry = await loadRegistry(registryPath);
    const entry = registry.projects.find((row) =>
      row.project === "X-LocalDesk"
    );
    validateServiceRegistry(entry, registryPath, root, settings);
    registryTool = join(
      registryWorkspaceRoot(registryPath),
      ".runtime/ports.ts",
    );
    await Deno.stat(
      join(registryWorkspaceRoot(registryPath), ".runtime/run-project.sh"),
    );
    await checked(Deno.execPath(), [
      "run",
      "--allow-read",
      registryTool,
      "validate",
    ]);
    if (
      options.install &&
      (entry!.runtime.kind !== "web" ||
        resolve(
            registryWorkspaceRoot(registryPath),
            entry!.runtime.composeFile ?? "",
          ) !==
          generated.composePath ||
        entry!.runtime.launchAgentLabel !== options.label)
    ) {
      throw new Error(
        "Registry runtime metadata must point to this generated compose and label before install",
      );
    }
  }
  const target = join(home, "Library/LaunchAgents", `${options.label}.plist`);
  const uid = (await checked("/usr/bin/id", ["-u"], 5000)).trim();
  const domain = `gui/${uid}`;
  // All labels generated by this checkout share its compose path. A new label
  // must not replace configuration beneath an already-running LocalDesk manager.
  const labels = new Set([options.label]);
  try {
    for await (const file of Deno.readDir(generated.runtime)) {
      if (file.isFile && /^[A-Za-z0-9][A-Za-z0-9.-]*\.plist$/.test(file.name)) {
        labels.add(file.name.slice(0, -6));
      }
    }
  } catch (error) {
    if (!(error instanceof Deno.errors.NotFound)) throw error;
  }
  for (const label of labels) {
    const loaded = await command("/bin/launchctl", [
      "print",
      `${domain}/${label}`,
    ], 5000);
    if (loaded.ok) {
      throw new Error(
        `LaunchAgent ${label} is already loaded; this command never overwrites or restarts an active service`,
      );
    }
  }
  if (options.install) {
    const existing = await textIfPresent(target);
    if (existing !== null && existing !== generated.plist) {
      throw new Error(`Installed plist conflicts: ${target}`);
    }
    for (
      const path of [
        settings.workspace,
        settings.projectsRoot,
        join(root, "frontend/dist"),
      ]
    ) {
      if (!(await Deno.stat(path)).isDirectory) {
        throw new Error("Run setup and build before installing");
      }
    }
    checkFreePorts(settings);
  }
  await Deno.mkdir(generated.runtime, { recursive: true, mode: 0o700 });
  await atomicWrite(generated.composePath, generated.compose);
  await atomicWrite(generated.plistPath, generated.plist);
  if (registryPath) {
    // The explicit workspace adapter discovers project-local plist sources here.
    // This compatibility copy is ignored machine-specific output, never source.
    const deploy = join(root, "deploy");
    await Deno.mkdir(deploy, { recursive: true, mode: 0o700 });
    await atomicWrite(join(deploy, `${options.label}.plist`), generated.plist);
  }
  await checked(
    processCompose,
    ["--dry-run", "--no-server", "--config", generated.composePath],
    15000,
    generated.environment,
  );
  await checked("/usr/bin/plutil", ["-lint", generated.plistPath]);
  console.log(
    `Validated compose: ${generated.composePath}\nValidated LaunchAgent: ${generated.plistPath}\nTarget: ${target}`,
  );
  if (!options.install) {
    console.log("Dry run complete; no LaunchAgent installed or started.");
    return;
  }
  // Recheck after validation. Port races fail visibly; no listener is ever killed.
  checkFreePorts(settings);
  if (
    (await command(
      "/bin/launchctl",
      ["print", `${domain}/${options.label}`],
      5000,
    )).ok
  ) throw new Error("Target LaunchAgent became loaded during validation");
  await Deno.mkdir(dirname(target), { recursive: true });
  const existing = await textIfPresent(target);
  if (existing !== null && existing !== generated.plist) {
    throw new Error("Target plist changed during validation");
  }
  if (existing === null) {
    await Deno.writeTextFile(target, generated.plist, {
      createNew: true,
      mode: 0o600,
    });
  }
  if (await Deno.readTextFile(target) !== generated.plist) {
    throw new Error("Installed plist readback mismatch");
  }
  await checked("/usr/bin/plutil", ["-lint", target]);
  await checked("/bin/launchctl", ["bootstrap", domain, target]);
  try {
    await waitHealthy(domain, options.label, generated.composePath, settings);
    if (registryTool) {
      const shared = [
        "run",
        "--allow-read",
        "--allow-run",
        "--allow-net",
        "--allow-ffi",
        "--allow-write",
        registryTool,
      ];
      await checked(
        Deno.execPath(),
        [...shared, "check-lan", "X-LocalDesk"],
        30000,
      );
      await checked(
        Deno.execPath(),
        [...shared, "check-web", "X-LocalDesk"],
        60000,
      );
    }
  } catch (error) {
    // Stop only the label bootstrapped by this invocation if acceptance fails.
    await checked("/bin/launchctl", ["bootout", `${domain}/${options.label}`]);
    throw new Error(
      `Installed runtime failed acceptance and its new service was stopped: ${
        String(error)
      }`,
    );
  }
  console.log(
    `Installed and verified ${options.label}; frontend ${settings.frontendPort}, backend ${settings.backendPort}.`,
  );
}

if (import.meta.main) await main(Deno.args);
